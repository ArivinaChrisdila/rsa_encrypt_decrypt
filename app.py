    "def cek_prima(n):\n",
    "    \"\"\"Memeriksa apakah n merupakan bilangan prima.\"\"\"\n",
    "    if n < 2:\n",
    "        return False\n",
    "    if n == 2:\n",
    "        return True\n",
    "    if n % 2 == 0:\n",
    "        return False\n",
